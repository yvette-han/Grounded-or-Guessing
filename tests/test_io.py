"""Tests for common/io.py: config inheritance, per-model folders, model guard."""

import json
from pathlib import Path

import pytest

from common.io import check_model, load_config, run_dir


def test_load_config_extends_overrides_only_named_keys(tmp_path):
    (tmp_path / "base.yaml").write_text("model: A\nseed: 354\ndecoding:\n  greedy: {do_sample: false}\n")
    (tmp_path / "sub").mkdir()
    (tmp_path / "sub" / "other.yaml").write_text("extends: ../base.yaml\nmodel: B\nrun_name: b\n")
    cfg = load_config(tmp_path / "sub" / "other.yaml")
    assert cfg == {"model": "B", "seed": 354, "decoding": {"greedy": {"do_sample": False}}, "run_name": "b"}


def test_load_config_without_extends_is_plain_yaml(tmp_path):
    (tmp_path / "c.yaml").write_text("model: A\n")
    assert load_config(tmp_path / "c.yaml") == {"model": "A"}


def test_repo_config_has_no_run_name():
    # the main Qwen run keeps the original folders (gen/, labels/, ...)
    cfg = load_config(Path(__file__).resolve().parents[1] / "config.yaml")
    assert not cfg.get("run_name")
    assert run_dir(cfg, "/r", "gen") == Path("/r/gen")


def test_run_dir_with_run_name():
    assert run_dir({"run_name": "llama"}, "/r", "gen") == Path("/r/gen/llama")
    assert run_dir({"run_name": "llama"}, "/r", "analysis/figures") == Path("/r/analysis/figures/llama")
    assert run_dir({"run_name": ""}, "/r", "labels") == Path("/r/labels")


def test_check_model():
    check_model([{"model": "A"}, {"model": "A"}], "A", "f")
    check_model([{"id": 1}], "A", "f")                  # old answers without the field pass
    with pytest.raises(SystemExit, match="generated by"):
        check_model([{"model": "A"}, {"model": "B"}], "A", "f")


def test_generate_resume_refuses_other_model(tmp_path):
    from gen.generate import read_done

    path = tmp_path / "answers_greedy.jsonl"
    path.write_text(json.dumps({"id": "q1", "model": "A"}) + "\n")
    assert read_done(path, "A") == {"q1"}
    assert read_done(path) == {"q1"}
    with pytest.raises(SystemExit):
        read_done(path, "B")
