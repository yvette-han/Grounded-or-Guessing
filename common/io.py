"""Small file helpers shared by the scripts."""

import json
from collections import OrderedDict


def read_jsonl(path):
    """All records of a .jsonl file, skipping blank lines."""
    with open(path) as f:
        return [json.loads(line) for line in f if line.strip()]


def group_records(records):
    """id -> list of (row index, record), keeping file order.

    The row index is the record's line in the file: the `row` join key of
    baseline/ and features/ outputs (README 7).
    """
    groups = OrderedDict()
    for row, r in enumerate(records):
        groups.setdefault(r["id"], []).append((row, r))
    return groups


# Config and per-model output folders ----------------------------------------

def load_config(path):
    """config.yaml as a dict. A config with `extends: <file>` starts from that
    file (path relative to this one) and overrides only the keys it names, so
    a second model's config can be just `extends`, `model` and `run_name`."""
    import yaml
    from pathlib import Path

    path = Path(path)
    with open(path) as f:
        cfg = yaml.safe_load(f) or {}
    base = cfg.pop("extends", None)
    if base:
        merged = load_config(path.parent / base)
        merged.update(cfg)
        cfg = merged
    return cfg


def run_dir(cfg, root, folder):
    """Default output folder for one pipeline step: `root/folder` for the main
    run, `root/folder/<run_name>` when the config sets `run_name` (another
    model), so runs of different models never overwrite each other."""
    from pathlib import Path

    name = cfg.get("run_name")
    return Path(root) / folder / name if name else Path(root) / folder


def check_model(answers, model, path):
    """Stop if an answers file was generated by a different model than the one
    about to tokenize or score it (token offsets would silently be wrong).
    Answers written before the `model` field existed are not checked."""
    found = {a["model"] for a in answers if a.get("model")}
    other = found - {model}
    if other:
        raise SystemExit(f"{path} was generated by {sorted(other)}, but the config model is {model!r}; "
                         f"pass the matching --config")
